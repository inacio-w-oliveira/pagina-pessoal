const STORAGE_KEY = 'iwo.lang';
const SUPPORTED = ['pt', 'en'];

/** Idioma ativo: ?lang= → localStorage → pt */
export function getLang() {
  const fromUrl = new URLSearchParams(window.location.search).get('lang');
  if (fromUrl && SUPPORTED.includes(fromUrl)) return fromUrl;

  try {
    const stored = localStorage.getItem(STORAGE_KEY);
    if (stored && SUPPORTED.includes(stored)) return stored;
  } catch (e) {
    /* storage indisponível */
  }

  return 'pt';
}

/** Traduz uma chave, com fallback para português. */
export function t(key, lang = getLang()) {
  const dict = translations[lang] || translations.pt;
  const value = dict[key] ?? translations.pt[key];

  if (value === undefined) {
    console.warn('[i18n] chave ausente:', key);
    return '';
  }

  return value;
}

function applyAttributeTranslations(lang) {
  document.querySelectorAll('[data-i18n-attr]').forEach((el) => {
    el.getAttribute('data-i18n-attr')
      .split(',')
      .forEach((pair) => {
        const [attr, key] = pair.split(':').map((part) => part.trim());
        if (!attr || !key) return;
        el.setAttribute(attr, t(key, lang));
      });
  });
}

/** Aplica todas as traduções no documento. */
export function applyTranslations(lang) {
  document.documentElement.lang = lang === 'en' ? 'en' : 'pt-BR';

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n, lang);
  });

  applyAttributeTranslations(lang);

  document.title = t('meta.title', lang);

  const description = document.querySelector('meta[name="description"]');
  if (description) description.setAttribute('content', t('meta.description', lang));

  const ogTitle = document.querySelector('meta[property="og:title"]');
  if (ogTitle) ogTitle.setAttribute('content', t('meta.title', lang));

  const ogDescription = document.querySelector('meta[property="og:description"]');
  if (ogDescription) ogDescription.setAttribute('content', t('meta.description', lang));

  document.querySelectorAll('[data-lang]').forEach((btn) => {
    const label = t(btn.dataset.lang === 'en' ? 'lang.en' : 'lang.pt', lang);
    btn.setAttribute('aria-pressed', String(btn.dataset.lang === lang));
    btn.setAttribute('aria-label', `${label} (${btn.textContent.trim()})`);
  });

  document.dispatchEvent(new CustomEvent('iwo:langchange', { detail: { lang } }));
}

/** Define e persiste o idioma ativo. */
export function setLang(lang) {
  const next = SUPPORTED.includes(lang) ? lang : 'pt';

  try {
    localStorage.setItem(STORAGE_KEY, next);
  } catch (e) {
    /* storage indisponível */
  }

  applyTranslations(next);
  return next;
}

/** Liga o seletor de idioma e aplica o idioma inicial. */
export function initI18n() {
  document.querySelectorAll('[data-lang]').forEach((btn) => {
    btn.addEventListener('click', () => setLang(btn.dataset.lang));
  });

  const initial = getLang();
  applyTranslations(initial);
  return initial;
}
